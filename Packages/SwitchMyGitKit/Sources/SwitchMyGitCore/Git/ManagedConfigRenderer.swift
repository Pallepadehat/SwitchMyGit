import Foundation

/// The Git configuration files SwitchMyGit owns, rendered as text.
public struct ManagedConfigFiles: Equatable, Sendable {
    /// `switchmygit.gitconfig`, the single file included from `~/.gitconfig`.
    public var entry: String
    /// `default.gitconfig`, the identity used when no rule matches.
    public var defaultIdentity: String
    /// `profiles/<id>.gitconfig` for every profile.
    public var profiles: [UUID: String]
}

/// Compiles a ``SwitcherConfiguration`` into Git configuration files.
///
/// This type is pure — it performs no I/O — which keeps the precedence logic
/// easy to read and to test.
public struct ManagedConfigRenderer: Sendable {
    public let paths: SwitcherPaths

    public init(paths: SwitcherPaths) {
        self.paths = paths
    }

    static let header = """
    # This file is generated by SwitchMyGit. Manual changes will be overwritten.
    # Edit your profiles and rules in the SwitchMyGit app instead.
    """

    public func render(_ configuration: SwitcherConfiguration) -> ManagedConfigFiles {
        var profiles: [UUID: String] = [:]
        for profile in configuration.profiles {
            profiles[profile.id] = renderProfile(profile)
        }

        return ManagedConfigFiles(
            entry: renderEntry(configuration),
            defaultIdentity: configuration.defaultProfile.map(renderProfile) ?? Self.header + "\n# No default profile selected.\n",
            profiles: profiles
        )
    }

    // MARK: - Entry file

    /// The default identity comes first, then rules from least to most
    /// specific. Git keeps the *last* value it reads, so a more specific rule
    /// always wins over a broader one, and every rule wins over the default.
    func renderEntry(_ configuration: SwitcherConfiguration) -> String {
        var lines = [Self.header, "", "[include]", "\tpath = \(GitConfigSyntax.quoteValue("default.gitconfig"))"]

        for rule in Self.orderedByPrecedence(configuration.activeRules) {
            guard let profile = configuration.profile(withID: rule.profileID) else { continue }
            let include = "profiles/\(profile.id.uuidString.lowercased()).gitconfig"
            lines.append("")
            lines.append("# \(rule.kind == .directory ? "Directory" : "Remote") rule → \(profile.name)")
            for condition in conditions(for: rule) {
                lines.append("[includeIf \(GitConfigSyntax.quoteSubsection(condition))]")
                lines.append("\tpath = \(GitConfigSyntax.quoteValue(include))")
            }
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// Sorts rules so that later entries take precedence over earlier ones:
    /// directory rules (shallow → deep), then remote rules (broad → narrow).
    public static func orderedByPrecedence(_ rules: [RepositoryRule]) -> [RepositoryRule] {
        rules.sorted { lhs, rhs in
            if lhs.kind != rhs.kind { return lhs.kind == .directory }
            let lhsDepth = specificity(of: lhs), rhsDepth = specificity(of: rhs)
            if lhsDepth != rhsDepth { return lhsDepth < rhsDepth }
            return lhs.pattern.localizedStandardCompare(rhs.pattern) == .orderedAscending
        }
    }

    private static func specificity(of rule: RepositoryRule) -> Int {
        rule.pattern.split(whereSeparator: { $0 == "/" || $0 == ":" }).count
    }

    /// The `includeIf` conditions for a rule.
    func conditions(for rule: RepositoryRule) -> [String] {
        switch rule.kind {
        case .directory:
            // `/i` makes matching case-insensitive, like the default macOS file system.
            ["gitdir/i:" + RulePattern.normalizedDirectory(rule.pattern, home: paths.home)]
        case .remote:
            RulePattern.remoteURLGlobs(for: rule.pattern).map { "hasconfig:remote.*.url:" + $0 }
        }
    }

    // MARK: - Profile files

    func renderProfile(_ profile: GitProfile) -> String {
        var lines = [Self.header, "# Profile: \(profile.name)", "", "[user]"]
        lines.append("\tname = \(GitConfigSyntax.quoteValue(profile.userName))")
        lines.append("\temail = \(GitConfigSyntax.quoteValue(profile.email))")

        if let keyPath = profile.normalizedSSHKeyPath {
            let absoluteKeyPath = PathFormatter(home: paths.home).expand(keyPath)
            let command = "ssh -i \(GitConfigSyntax.shellQuote(absoluteKeyPath)) -o IdentitiesOnly=yes"
            lines += ["", "[core]", "\tsshCommand = \(GitConfigSyntax.quoteValue(command))"]
        }
        return lines.joined(separator: "\n") + "\n"
    }
}
